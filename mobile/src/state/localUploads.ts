/**
 * Optimistic client-side tracking for a video upload that's still in
 * flight — deliberately NOT React state/context. App.tsx's
 * handleVideoConfirmed (where an upload actually starts) renders OUTSIDE
 * VideoJobsProvider's own subtree (it's the component that instantiates
 * the provider, not a descendant of it), so it can't call
 * useVideoJobsContext(). A plain module-level store that anything can
 * write to, paired with useVideoJobs.ts reading it via
 * React's useSyncExternalStore, sidesteps that without prop-drilling or
 * restructuring the component tree.
 *
 * Exists so "N videos processing" can count an upload the INSTANT the
 * athlete confirms a recording — before the network request has even
 * started, let alone before a real video_jobs row exists — instead of
 * waiting for the upload to finish and the row to be inserted (a real
 * network round-trip that visibly lagged the banner behind the athlete's
 * own action). A local upload's `id` is generated by the caller BEFORE
 * starting the upload (see api/videoJobs.ts's generateJobId) and reused as
 * the real video_jobs row's id once the upload succeeds — useVideoJobs.ts
 * prunes an entry the moment a real job with the same id shows up, so
 * there's no separate "swap" step, just a clean handoff.
 */
import { ExerciseKey } from '../utils/exerciseMetrics';

export interface LocalUpload {
  id: string;
  status: 'uploading' | 'failed';
  durationSec: number;
  recordedAt: string;
  targetExerciseKey: ExerciseKey | null;
  errorMessage: string | null;
}

type Listener = () => void;

let uploads: LocalUpload[] = [];
const listeners = new Set<Listener>();

function emit(): void {
  listeners.forEach((l) => l());
}

export function subscribeLocalUploads(listener: Listener): () => void {
  listeners.add(listener);
  return () => { listeners.delete(listener); };
}

export function getLocalUploadsSnapshot(): LocalUpload[] {
  return uploads;
}

export function addLocalUpload(params: { id: string; durationSec: number; targetExerciseKey: ExerciseKey | null }): void {
  uploads = [
    ...uploads,
    { id: params.id, status: 'uploading', durationSec: params.durationSec, recordedAt: new Date().toISOString(), targetExerciseKey: params.targetExerciseKey, errorMessage: null },
  ];
  emit();
}

export function markLocalUploadFailed(id: string, errorMessage: string): void {
  uploads = uploads.map((u) => (u.id === id ? { ...u, status: 'failed', errorMessage } : u));
  emit();
}

// Called both for an explicit dismiss (the failed banner's "X") and
// internally once a local upload's real video_jobs counterpart appears —
// see useVideoJobs.ts's refetch reconciliation.
export function removeLocalUpload(id: string): void {
  uploads = uploads.filter((u) => u.id !== id);
  emit();
}

export function removeLocalUploadsByStatus(status: LocalUpload['status']): void {
  uploads = uploads.filter((u) => u.status !== status);
  emit();
}
